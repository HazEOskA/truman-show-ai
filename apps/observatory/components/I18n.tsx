type ContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Values) => string;
  term: (value: unknown) => string;
};

const I18nContext = createContext<ContextValue | null>(null);

function interpolate(template: string, values?: Values): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

function termKey(value: unknown): string {
  return String(value ?? "").trim().toLowerCase().replace(/[\s_]+/g, "-");
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("pl");

  useEffect(() => {
    const saved = window.localStorage.getItem("hydra-language");
    if (saved === "pl" || saved === "en") setLanguageState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    window.localStorage.setItem("hydra-language", language);
  }, [language]);

  const setLanguage = useCallback((next: Language) => setLanguageState(next), []);
  const value = useMemo<ContextValue>(() => {
    const index = language === "pl" ? 0 : 1;
    const t = (key: string, values?: Values) => interpolate(TEXT[key]?.[index] ?? key, values);
    return {
      language,
      setLanguage,
      t,
      term: (raw: unknown) => {
        const source = String(raw ?? "");
        return TEXT[`value.${termKey(raw)}`]?.[index] ?? source.replace(/_/g, " ");
      }
    };
  }, [language, setLanguage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): ContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}

export function LanguageSwitch({ compact = false }: { compact?: boolean }) {
  const { language, setLanguage, t } = useI18n();
  return (
    <div className={compact ? "language-switch language-switch--compact" : "language-switch"} aria-label={t("a11y.language")} role="group">
      <button type="button" lang="pl" aria-pressed={language === "pl"} className={language === "pl" ? "is-active" : ""} onClick={() => setLanguage("pl")}>PL</button>
      <span aria-hidden="true">|</span>
      <button type="button" lang="en" aria-pressed={language === "en"} className={language === "en" ? "is-active" : ""} onClick={() => setLanguage("en")}>EN</button>
    </div>
  );
}
